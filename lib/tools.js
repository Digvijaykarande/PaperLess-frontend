export const getTool = (slug) => TOOLS.find((t) => t.slug === slug)
export const getFeaturedTools = () => TOOLS.filter((t) => t.featured)
export const getRelatedTools = (tool, count = 4) =>
  TOOLS.filter((t) => t.slug !== tool.slug && t.category === tool.category)
    .concat(TOOLS.filter((t) => t.category !== tool.category))
    .slice(0, count)
